// Regenerates src/components/qr.js, the QR code drawn in the IntelliQrHelp
// wireframe. Needs the qrcode package once:
//   npm i -D qrcode && node scripts/make-qr.mjs https://tinyurl.com/intelliqrhelp
import { writeFile } from 'node:fs/promises'
import QRCode from 'qrcode'

const url = process.argv[2]
if (!url) throw new Error('Usage: node scripts/make-qr.mjs <url>')

const qr = QRCode.create(url, { errorCorrectionLevel: 'M' })
const n = qr.modules.size
const dark = qr.modules.data
let path = ''
for (let y = 0; y < n; y++) {
  for (let x = 0; x < n; ) {
    if (!dark[y * n + x]) {
      x++
      continue
    }
    let w = 1
    while (x + w < n && dark[y * n + x + w]) w++
    path += `M${x} ${y}h${w}v1h-${w}z`
    x += w
  }
}

await writeFile(
  new URL('../src/components/qr.js', import.meta.url),
  `// QR code for ${url} (version ${qr.version}, error correction M).
// Generated by scripts/make-qr.mjs; each dark run of modules is one subpath.
export const INTELLIQRHELP_QR = {
  url: ${JSON.stringify(url)},
  size: ${n},
  path: ${JSON.stringify(path)},
}
`,
)
console.log(`wrote src/components/qr.js (${n}×${n})`)
